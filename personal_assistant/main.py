def get_mood():
    mood = input("Какое у тебя настроение? (хорошее/плохое) ").lower()

    if mood == "хорошее":
        print("Отлично! У тебя будет продуктивный день!")
        return
    elif mood == "плохое":
        print("Не расстраивайся! Всё обязательно наладится!")
        return
    else:
        print("Надеюсь, у тебя всё хорошо!")
        return

